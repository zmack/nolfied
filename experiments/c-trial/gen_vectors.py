#!/usr/bin/env python3
"""Random claim scenarios shared by the C and the assembly benchmark.

Record (24 bytes): chips u16, chain u8, kills u8, stage_mult u16,
perks_owned u8, pad u8, stacks[16].
"""
import random
import struct
import sys

MAX = [9, 5, 3, 5, 5, 1, 3, 3, 3, 9, 2, 5, 1, 3, 5, 3]
N = 40
rnd = random.Random(816)
recs = []
for i in range(N):
    stacks = [rnd.randint(0, m) if rnd.random() < 0.4 else 0 for m in MAX]
    chips = rnd.choice([rnd.randint(1, 39), rnd.randint(40, 149), rnd.randint(150, 900), rnd.randint(900, 2668)])
    recs.append((chips, rnd.randint(0, 20), rnd.randint(0, 7), rnd.choice([0, 0, 4, 8, 24]),
                 sum(stacks), stacks))
# corner cases: no perks; the 999 cap
recs[0] = (220, 0, 0, 0, 0, [0] * 16)
recs[1] = (2600, 20, 7, 40, 40, [9, 5, 3, 0, 5, 0, 0, 0, 0, 0, 0, 5, 1, 0, 0, 0])
out = b""
for chips, chain, kills, jack, owned, stacks in recs:
    out += struct.pack("<HBBHBB16B", chips, chain, kills, jack, owned, 0, *stacks)
open(sys.argv[1], "wb").write(out)
with open(sys.argv[2], "w") as f:
    f.write("/* generated by gen_vectors.py */\n#define N_VECTORS %d\n" % N)
    f.write("static const unsigned char vectors[%d] = {\n" % len(out))
    for i in range(0, len(out), 24):
        f.write("    " + ", ".join(str(b) for b in out[i:i + 24]) + ",\n")
    f.write("};\n")
